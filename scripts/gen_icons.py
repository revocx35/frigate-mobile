#!/usr/bin/env python3
"""Regenerates app/src/main/java/.../ui/theme/AppIcons.kt from Google's Material Symbols SVGs.

Add an entry to ICONS (Kotlin name -> Material Symbols name, see https://fonts.google.com/icons) and run:
    python3 scripts/gen_icons.py
"""
import os
import re
import urllib.request

ICONS = {
    'Videocam': 'videocam', 'Review': 'video_library', 'Settings': 'settings', 'Back': 'arrow_back',
    'Refresh': 'refresh', 'Check': 'check', 'CheckCircle': 'check_circle', 'DoneAll': 'done_all', 'Error': 'error',
    'Warning': 'warning', 'Info': 'info', 'Visibility': 'visibility', 'VisibilityOff': 'visibility_off',
    'Logout': 'logout', 'Person': 'person', 'Lock': 'lock', 'Close': 'close', 'Fullscreen': 'fullscreen',
    'FullscreenExit': 'fullscreen_exit', 'Play': 'play_arrow', 'Movie': 'movie', 'Filter': 'filter_list',
    'MoreVert': 'more_vert', 'Memory': 'memory', 'Storage': 'hard_drive', 'Calendar': 'calendar_month',
    'Camera': 'photo_camera', 'Shield': 'shield', 'Lan': 'lan', 'ChevronRight': 'chevron_right',
    'Share': 'share', 'Image': 'image', 'Motion': 'directions_run', 'Car': 'directions_car', 'Pets': 'pets',
    'Notifications': 'notifications', 'NotificationsOff': 'notifications_off', 'Speed': 'speed',
    'Record': 'radio_button_checked', 'Mic': 'mic', 'Schedule': 'schedule', 'Bug': 'bug_report',
    'ExpandMore': 'expand_more', 'Grid': 'grid_view', 'Stream': 'stream', 'Server': 'host', 'Copy': 'content_copy',
    'Hd': 'hd', 'Sd': 'sd', 'Snapshot': 'add_a_photo', 'Detect': 'center_focus_strong',
    'ArrowUp': 'keyboard_arrow_up', 'ArrowDown': 'keyboard_arrow_down', 'ArrowLeft': 'keyboard_arrow_left',
    'ArrowRight': 'keyboard_arrow_right', 'ZoomIn': 'zoom_in', 'ZoomOut': 'zoom_out', 'VolumeUp': 'volume_up',
    'VolumeOff': 'volume_off', 'Ptz': 'control_camera', 'Bookmark': 'bookmark', 'Timeline': 'view_timeline',
}

URL = 'https://fonts.gstatic.com/s/i/short-term/release/materialsymbolsoutlined/{}/default/24px.svg'
OUT = os.path.join(os.path.dirname(__file__), '..', 'app/src/main/java/io/github/revocx35/frigatemobile/ui/theme/AppIcons.kt')

lines = [
    'package io.github.revocx35.frigatemobile.ui.theme',
    '',
    'import androidx.compose.ui.graphics.Color',
    'import androidx.compose.ui.graphics.SolidColor',
    'import androidx.compose.ui.graphics.vector.ImageVector',
    'import androidx.compose.ui.graphics.vector.addPathNodes',
    'import androidx.compose.ui.unit.dp',
    '',
    '/**',
    ' * Material Symbols (Outlined, weight 400) used by the app. Generated by scripts/gen_icons.py from Google\'s',
    ' * published SVGs (Apache 2.0), so only these icons ship instead of the whole icon library. Do not edit by hand.',
    ' */',
    'object AppIcons {',
]
for name, symbol in ICONS.items():
    svg = urllib.request.urlopen(URL.format(symbol), timeout=30).read().decode()
    paths = re.findall(r' d="([^"]+)"', svg)
    if not paths:
        raise SystemExit(f'no path in {symbol}')
    lines.append(f'    val {name}: ImageVector by lazy {{ icon("{symbol}", "{" ".join(paths)}") }}')
lines += [
    '',
    '    private fun icon(name: String, pathData: String): ImageVector =',
    '        ImageVector.Builder(name, 24.dp, 24.dp, viewportWidth = 960f, viewportHeight = 960f)',
    '            // Material Symbols use viewBox="0 -960 960 960".',
    '            .addGroup(translationY = 960f)',
    '            .addPath(pathData = addPathNodes(pathData), fill = SolidColor(Color.Black))',
    '            .clearGroup()',
    '            .build()',
    '}',
    '',
]
with open(OUT, 'w') as f:
    f.write('\n'.join(lines))
print(f'{len(ICONS)} icons -> {os.path.normpath(OUT)}')
